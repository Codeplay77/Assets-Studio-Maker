// Portuguese names for the furniture packs, and how each piece is mounted.
//
// `w` hangs on a wall (its back touches the wall) and `c` hangs from the ceiling. Everything else
// stands on the floor.

export type Mount = "floor" | "w" | "c";

export interface InteriorName {
  label: string;
  mount?: Mount;
}

const n = (label: string, mount?: Mount): InteriorName => (mount ? { label, mount } : { label });

